package com.projectguard.backend.registry;

/**
 * 업로드된 등기부등본의 종류. 첫 줄의 "[집합건물]" / "[건물]" / "[토지]" 표시로 구분한다.
 * 사용자가 고른 부동산 유형과 맞는지 확인하는 데 쓴다 — 유형을 잘못 고르면 판정 기준 자체가 달라진다.
 */
public enum RegistryKind {
    /** 아파트·오피스텔·빌라(연립·다세대). 호실마다 등기부가 따로 있다. */
    COLLECTIVE_BUILDING,
    /** 단독주택·다가구주택 등. 건물 전체에 등기부가 하나다. */
    BUILDING,
    /** 토지 등기부. 건물 분석에는 쓸 수 없다. */
    LAND,
    /** 표시를 찾지 못함 (촬영 이미지에서 첫 페이지가 빠진 경우 등). */
    UNKNOWN
}
