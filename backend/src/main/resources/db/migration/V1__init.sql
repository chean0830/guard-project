create table admin_auth_tokens (
    expires_at timestamp(6) with time zone not null,
    token varchar(255) not null,
    primary key (token)
);

create table admin_messages (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    lawyer_id bigint not null,
    read_at timestamp(6) with time zone,
    content varchar(2000) not null,
    primary key (id)
);

create table app_login_codes (
    expires_at timestamp(6) with time zone not null,
    code_challenge varchar(64) not null,
    code_hash varchar(64) not null,
    email varchar(255) not null,
    session_token varchar(255) not null,
    primary key (code_hash)
);

create table auth_tokens (
    expires_at timestamp(6) with time zone not null,
    user_id bigint not null,
    token varchar(255) not null,
    primary key (token)
);

create table chat_blocks (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    lawyer_id bigint not null,
    user_id bigint not null,
    blocker_type varchar(30) not null check ((blocker_type in ('USER','LAWYER'))),
    primary key (id),
    unique (blocker_type, user_id, lawyer_id)
);

create table consultation_messages (
    read boolean not null,
    consultation_id bigint not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    content varchar(2000) not null,
    sender_type varchar(30) not null check ((sender_type in ('USER','LAWYER'))),
    primary key (id)
);

create table consultations (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    last_message_at timestamp(6) with time zone not null,
    lawyer_id bigint not null,
    user_id bigint not null,
    primary key (id)
);

create table device_push_tokens (
    id bigint generated by default as identity,
    owner_id bigint not null,
    updated_at timestamp(6) with time zone not null,
    platform varchar(20),
    token varchar(512) not null unique,
    owner_type varchar(30) not null check ((owner_type in ('USER','LAWYER'))),
    primary key (id)
);

create table email_verifications (
    failed_attempts integer not null,
    code_expires_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    used_at timestamp(6) with time zone,
    verified_at timestamp(6) with time zone,
    code_hash varchar(255) not null,
    email varchar(255) not null,
    token_hash varchar(255) unique,
    primary key (id)
);

create table lawyer_auth_tokens (
    expires_at timestamp(6) with time zone not null,
    lawyer_id bigint not null,
    token varchar(255) not null,
    primary key (token)
);

create table lawyer_credential_documents (
    id bigint generated by default as identity,
    lawyer_id bigint not null,
    uploaded_at timestamp(6) with time zone not null,
    content_type varchar(255) not null,
    file_name varchar(255) not null,
    data bytea not null,
    primary key (id)
);

create table lawyers (
    blocked boolean not null,
    career_years integer,
    email_notifications_enabled boolean not null,
    failed_login_count integer default 0 not null,
    login_locked boolean default false not null,
    blocked_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    reviewed_at timestamp(6) with time zone,
    headline varchar(100),
    fee_info varchar(300),
    achievements varchar(1000),
    introduction varchar(1000),
    bar_number varchar(255) not null,
    blocked_reason varchar(255),
    email varchar(255) not null unique,
    law_firm varchar(255),
    name varchar(255) not null,
    password_hash varchar(255) not null,
    rejection_reason varchar(255),
    specialties varchar(255),
    status varchar(30) not null check ((status in ('PENDING','APPROVED','REJECTED'))),
    primary key (id)
);

create table password_reset_tokens (
    account_id bigint not null,
    expires_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    used_at timestamp(6) with time zone,
    account_type varchar(255) not null,
    token_hash varchar(255) not null unique,
    primary key (id)
);

create table payment_orders (
    amount bigint not null,
    canceled_at timestamp(6) with time zone,
    consultation_id bigint,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    paid_at timestamp(6) with time zone,
    refund_requested_at timestamp(6) with time zone,
    used_at timestamp(6) with time zone,
    user_id bigint not null,
    refund_reason varchar(500),
    refund_rejected_reason varchar(500),
    order_id varchar(255) not null unique,
    payment_key varchar(255) unique,
    product_type varchar(30) default 'LAWYER_SELECTION' not null check ((product_type in ('LAWYER_SELECTION','ANALYSIS'))),
    status varchar(30) not null check ((status in ('READY','PAID','FAILED','CANCELED','REFUND_REQUESTED','REFUNDED'))),
    primary key (id)
);

create table push_subscriptions (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    endpoint varchar(1000) not null unique,
    auth varchar(255) not null,
    p256dh varchar(255) not null,
    primary key (id)
);

create table rate_limit_counters (
    usage_count integer not null,
    usage_day date not null,
    id bigint generated by default as identity,
    counter_key varchar(120) not null,
    primary key (id),
    unique (counter_key, usage_day)
);

create table reports (
    consultation_id bigint not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    reporter_id bigint not null,
    resolved_at timestamp(6) with time zone,
    target_id bigint not null,
    detail varchar(1000),
    reason varchar(30) not null check ((reason in ('ABUSIVE_LANGUAGE','MONEY_REQUEST'))),
    reporter_type varchar(30) not null check ((reporter_type in ('USER','LAWYER'))),
    status varchar(30) not null check ((status in ('PENDING','ACTIONED','DISMISSED'))),
    target_type varchar(30) not null check ((target_type in ('USER','LAWYER'))),
    primary key (id)
);

create table users (
    blocked boolean not null,
    failed_login_count integer default 0 not null,
    login_locked boolean default false not null,
    blocked_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    blocked_reason varchar(255),
    email varchar(255) not null unique,
    name varchar(255),
    password_hash varchar(255),
    provider varchar(255) not null,
    provider_id varchar(255),
    primary key (id)
);

